// รับอาร์เรย์ผู้เล่นที่มีอยู่แล้วในห้อง (รูปแบบ [{ id, name }, ...] — ตรงกับ snap.docs.map((d) => ({ id:
// d.id, name: d.data().name })) จากฝั่งเรียกจริง) กับชื่อที่เพิ่งพิมพ์เข้ามา คืนค่า id ของผู้เล่นเดิมถ้าเจอ
// ชื่อตรงกัน (rejoin) หรือ null ถ้าไม่เจอ (เข้าห้องใหม่จริงๆ ผู้เรียกต้องสุ่ม id ใหม่เอง)
export function findExistingPlayerId(players, name) {
  const target = (name ?? "").trim().toLowerCase();
  if (!target) return null;
  const match = players.find((p) => (p.name ?? "").trim().toLowerCase() === target);
  return match ? match.id : null;
}
